#!/usr/bin/env node
// Build src/assets.js from public/*.png as base64 data URLs.
// Run: node scripts/build-assets.js (also runs as part of npm run build).
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
const out = join(root, 'src', 'assets.js');

// Only the images the UI actually displays. Keeps the Worker bundle lean.
// Agent mascots use the 3D set by default; the line-art set lives in public/
// as alternates and is intentionally not embedded.
const WANTED = {
  'yourkly-stork.png': 'IMG_YOURKLY_STORK',
  'yourkly-wordmark.png': 'IMG_YOURKLY_WORDMARK',
  'stork-fixer-3d.png': 'IMG_STORK_FIXER',
  'stork-builder-3d.png': 'IMG_STORK_BUILDER',
  'stork-polisher-3d.png': 'IMG_STORK_POLISHER',
  'stork-empty-basket.png': 'IMG_STORK_EMPTY_BASKET',
};

const files = readdirSync(pub).filter(f => f in WANTED).sort();
let js = '// Generated by scripts/build-assets.js. Do not edit by hand.\n';
for (const f of files) {
  const b64 = readFileSync(join(pub, f)).toString('base64');
  js += `export const ${WANTED[f]} = "data:image/png;base64,${b64}";\n`;
  console.log(`embedded ${f} as ${WANTED[f]} (${(b64.length / 1024).toFixed(0)} KB base64)`);
}
writeFileSync(out, js);
console.log('wrote src/assets.js');
