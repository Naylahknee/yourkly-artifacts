#!/usr/bin/env node
// Build src/assets.js from public/*.png as base64 data URLs.
// Run: node scripts/build-assets.js (also runs as part of npm run build).
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');
const out = join(root, 'src', 'assets.js');

// Only the images the UI actually displays. Keeps the Worker bundle lean.
const WANTED = [
  'yourkly-stork.png',
  'yourkly-wordmark.png',
  'stork-fixer.png',
  'stork-builder.png',
  'stork-polisher.png',
];

const files = readdirSync(pub).filter(f => WANTED.includes(f)).sort();
let js = '// Generated by scripts/build-assets.js. Do not edit by hand.\n';
for (const f of files) {
  const b64 = readFileSync(join(pub, f)).toString('base64');
  const name = f.replace(/\.png$/, '').replace(/[^a-z0-9]/gi, '_').toUpperCase();
  js += `export const IMG_${name} = "data:image/png;base64,${b64}";\n`;
  console.log(`embedded ${f} (${(b64.length / 1024).toFixed(0)} KB base64)`);
}
writeFileSync(out, js);
console.log('wrote src/assets.js');
